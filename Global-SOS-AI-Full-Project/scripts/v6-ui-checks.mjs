import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';

export async function checkV6(browser,origin){
 await mkdir('artifacts/web-previews',{recursive:true});
 const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
 await context.addInitScript(()=>localStorage.setItem('sos_country','IN'));
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 const go=name=>page.locator(`nav button[data-screen="${name}"]`).click();
 await page.goto(origin+'/mobile',{waitUntil:'networkidle'});
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-home-dark.png'});
 await go('All Helplines');await page.getByLabel('Search services').fill('no-such-service-zqxv');
 await page.getByLabel('Current country',{exact:true}).selectOption('US');
 assert.equal(await page.getByLabel('Search services').inputValue(),'','country change clears old filters');
 await go('AI Assistant');await page.goBack();
 await page.getByLabel('Search services').waitFor();await page.reload();
 await page.getByLabel('Search services').waitFor();
 const card=page.locator('.cards .service-card').first();await card.locator('summary').click();
 await card.locator('.star').click();assert.equal(await card.locator('details').getAttribute('open'),'','saving a favorite keeps details open');
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-directory.png'});
 await go('Home');await page.locator('.sos-orb').click();await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0,'Escape closes SOS preparation');
 let sessions=0;await page.route('**/api/sos',route=>{sessions++;return route.fulfill({json:{id:'fixture',capability:'fixture'}});});
 await page.locator('.sos-orb').click();await page.getByRole('button',{name:'Start without location',exact:true}).click();
 await go('All Helplines');await page.getByRole('button',{name:'Cancel countdown',exact:true}).click();
 await page.waitForTimeout(5500);assert.equal(sessions,0,'pinned cancellation works from another tab');
 await go('AI Assistant');await page.getByLabel('Allow online routing',{exact:false}).check();
 await page.getByLabel('Current country',{exact:true}).selectOption('IN');
 let release,seen;const gate=new Promise(resolve=>release=resolve),requested=new Promise(resolve=>seen=resolve);
 const source=JSON.parse(await readFile('shared/directory.json','utf8'));
 await page.route('**/api/chat',async route=>{seen();await gate;await route.fulfill({json:{message:'Old-country response',mode:'fixture',records:source.records.filter(r=>r.country==='IN').slice(0,1)}});});
 await page.getByLabel('Message',{exact:true}).fill('zqxv');await page.getByRole('button',{name:'Send',exact:false}).click();
 await Promise.race([requested,new Promise((_,reject)=>setTimeout(()=>reject(Error('Chat request was not issued')),8000))]);
 await page.getByLabel('Current country',{exact:true}).selectOption('US');
 const response=page.waitForResponse(r=>r.url().endsWith('/api/chat'));release();await response;await page.waitForTimeout(200);
 assert.equal(await page.getByText('Old-country response',{exact:true}).count(),0,'old assistant responses cannot cross countries');
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-assistant.png'});
 await go('My Safety');
 await page.getByRole('button',{name:'Tools',exact:true}).click();
 await page.getByText('Trip planner and calendar reminders',{exact:true}).click();
 await page.getByLabel('Destination',{exact:true}).fill('Fixture trip');
 await page.getByRole('button',{name:'Contacts',exact:true}).click();
 await page.getByRole('button',{name:'Tools',exact:true}).click();
 assert.equal(await page.getByLabel('Destination',{exact:true}).inputValue(),'Fixture trip','switching safety sections preserves a trip draft');
 await page.getByRole('button',{name:'Contacts',exact:true}).click();
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-safety.png'});
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByLabel('Light theme',{exact:true}).check();await go('Home');
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-home-light.png'});
 await page.setViewportSize({width:320,height:780});await page.getByLabel('Interface language').selectOption('ar');
 assert.ok(await page.locator('body').evaluate(el=>el.scrollWidth<=window.innerWidth),'Arabic 320px screen does not overflow');
 await page.getByLabel('Interface language').selectOption('en');
 await page.screenshot({path:'artifacts/web-previews/v6-mobile-320.png'});
 assert.deepEqual(errors,[]);await context.close();
 const desktop=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 await desktop.goto(origin+'/desktop',{waitUntil:'networkidle'});await desktop.getByLabel('Current country',{exact:true}).selectOption('IN');
 await desktop.screenshot({path:'artifacts/web-previews/v6-desktop-home.png'});
 await desktop.locator('nav button[data-screen="AI Assistant"]').click();
 await desktop.screenshot({path:'artifacts/web-previews/v6-desktop-assistant.png'});await desktop.close();
 const blocked=await browser.newContext({viewport:{width:390,height:844}});
 await blocked.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Blocked','SecurityError');};});
 const limited=await blocked.newPage();const limitedErrors=[];limited.on('pageerror',e=>limitedErrors.push(String(e)));
 await limited.goto(origin+'/mobile',{waitUntil:'networkidle'});
 await limited.getByText('Browser storage is unavailable.',{exact:false}).waitFor();
 await limited.locator('nav button[data-screen="SOS"]').click();await limited.getByRole('heading',{name:'Emergency controls',exact:true}).waitFor();
 assert.deepEqual(limitedErrors,[],'blocked browser storage does not crash emergency controls');await blocked.close();
 console.log('PASS v6: history/reload routing, country reset, stable source cards, Escape, pinned SOS cancellation, stale chat isolation, storage failure recovery, RTL and desktop/mobile captures');
}
